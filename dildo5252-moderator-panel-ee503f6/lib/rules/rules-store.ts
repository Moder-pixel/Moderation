function isBrowser(): boolean {
  return typeof window !== "undefined";
}

export function loadRulesData(): RulesData {
  if (!isBrowser()) return EMPTY_DATA;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw === null) {
      const seeded: RulesData = { version: 1, promotionCriteria: [] };
      localStorage.setItem(STORAGE_KEY, JSON.stringify(seeded));
      return seeded;
    }
    const parsed = JSON.parse(raw) as RulesData;
    if (
      !parsed ||
      parsed.version !== 1 ||
      !Array.isArray(parsed.promotionCriteria)
    ) {
      return EMPTY_DATA;
    }
    return parsed;
  } catch {
    return EMPTY_DATA;
  }
}

function saveRulesData(data: RulesData): void {
  if (!isBrowser()) return;
  localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
}

export function subscribeRulesStore(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

function refreshSnapshot(): void {
  cachedData = loadRulesData();
  for (const listener of listeners) {
    listener();
  }
}

export function getRulesSnapshot(): RulesData {
  if (cachedData === null) {
    cachedData = loadRulesData();
  }
  return cachedData;
}

export function getRulesServerSnapshot(): RulesData {
  return EMPTY_DATA;
}

export function setPromotionCriteria(text: string): Result {
  const paragraphs = text
    .split(/\r?\n/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean);
  const data = loadRulesData();
  data.promotionCriteria = paragraphs;
  saveRulesData(data);
  refreshSnapshot();
  return { ok: true, data: undefined };
}
